// randomAgentName: un nume la intamplare care nu e deja in echipa (taken = nume, orice litere)
// si nu e cel de acum (avoid), ca "zarul" sa schimbe mereu numele. Fallback: "New agent N".
export function randomAgentName(taken = [], avoid = "") {
  const used = new Set([...taken, avoid].map((n) => String(n).trim().toLowerCase()));
  const free = AGENT_NAMES.filter((n) => !used.has(n.toLowerCase()));
  if (free.length) return free[Math.floor(Math.random() * free.length)];
  let name = "New agent";
  for (let i = 2; used.has(name.toLowerCase()); i++) name = `New agent ${i}`;
  return name;
}
